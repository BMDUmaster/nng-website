// Writes src/content/offerings/pages/index.ts: one import for every page file in that folder, in the order of
// src/content/routes.json. Each page lives in its own file (pages/<hub>.ts for a hub, pages/<hub>--<slug>.ts for a
// page beneath it) exporting `page`, so pages can be written, reviewed and replaced one at a time.
//   node scripts/gen-offering-pages.mjs          (run by npm run export before every build)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "src/content/offerings/pages");
const routes = JSON.parse(fs.readFileSync(path.join(root, "src/content/routes.json"), "utf8"));
const order = routes
  .map((route) => route.path.match(/^\/services\/([a-z0-9-]+)\/(?:([a-z0-9-]+)\/)?$/))
  .filter(Boolean)
  .map((m) => (m[2] ? `${m[1]}--${m[2]}` : m[1]));
const files = fs
  .readdirSync(dir)
  .filter((name) => name.endsWith(".ts") && name !== "index.ts")
  .map((name) => name.slice(0, -3));
const unknown = files.filter((name) => !order.includes(name));
if (unknown.length) {
  console.error(`gen-offering-pages: no route for ${unknown.join(", ")}`);
  process.exit(1);
}
const present = order.filter((name) => files.includes(name));
const ident = (name) => `p_${name.replace(/[^a-z0-9]+/g, "_")}`;
const body = [
  "// Generated by scripts/gen-offering-pages.mjs from the page files in this folder. Do not edit by hand.",
  'import type { OfferingPage } from "../types";',
  ...present.map((name) => `import { page as ${ident(name)} } from "./${name}";`),
  "",
  `export const pages: OfferingPage[] = [${present.map(ident).join(", ")}];`,
  "",
].join("\n");
fs.writeFileSync(path.join(dir, "index.ts"), body);
console.log(`gen-offering-pages: ${present.length} of ${order.length} service pages present${present.length < order.length ? ` (missing: ${order.filter((n) => !present.includes(n)).join(", ")})` : ""}`);
